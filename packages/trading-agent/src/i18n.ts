export type TranslationParams = Record<string, string | number>;

export function translate(language: TradingLanguage, key: MenuKey, params?: TranslationParams): string {
	const template = (language === "zh-CN" ? MENU_ZH[key] : undefined) ?? MENU_EN[key];
	if (!params) return template;
	return template.replace(/\{([A-Za-z0-9_-]+)\}/g, (match, name: string) =>
		Object.hasOwn(params, name) ? String(params[name]) : match,
	);
}

export function t(language: TradingLanguage, key: MenuKey): string {
	return translate(language, key);
}

